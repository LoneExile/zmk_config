"""Draw toucan/toucan.keymap as keymap-drawer/toucan.svg.

Run from anywhere: uv run keymap-drawer/draw.py

The firmware keymap has 42 positions (beekeeb's 3x6+3 matrix). The 36-key
Toucan2 has no outer pinky column, so those 6 positions are dropped and the
diagram uses the 36-key geometry in toucan2_36.json (beekeeb's
default_layout without that column). A real binding on a dropped position,
or a combo using one, stops the script instead of vanishing from the
picture; empty and transparent keys there are dropped silently.
"""

import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
HERE = Path(__file__).resolve().parent
CONFIG = HERE / "config.yaml"
KEYMAP = ROOT / "toucan" / "toucan.keymap"
PARSED = HERE / "toucan.yaml"
SVG = HERE / "toucan.svg"
LAYOUT = "keymap-drawer/toucan2_36.json"  # relative to ROOT, written into toucan.yaml

MISSING = {0, 11, 12, 23, 24, 35}  # outer pinky column, absent on the 36-key board
POSITIONS = 42
KEEP = [p for p in range(POSITIONS) if p not in MISSING]
COMBOS = "COMBOS (every layer)"
NEW_INDEX = {old: new for new, old in enumerate(KEEP)}


def keymap_drawer(*args: str) -> str:
    cmd = [sys.executable, "-m", "keymap_drawer", "-c", str(CONFIG), *args]
    return subprocess.run(cmd, check=True, capture_output=True, text=True, cwd=ROOT).stdout


def is_blank(key) -> bool:
    return key in ("", None) or (isinstance(key, dict) and key.get("type") == "trans")


def main() -> None:
    parsed = yaml.safe_load(keymap_drawer("parse", "-z", str(KEYMAP)))

    for name, keys in parsed["layers"].items():
        if len(keys) != POSITIONS:
            sys.exit(f"layer {name}: {len(keys)} keys, expected {POSITIONS}")
        used = sorted(p for p in MISSING if not is_blank(keys[p]))
        if used:
            sys.exit(f"layer {name}: bindings on positions {used}, which the 36-key board lacks")
        parsed["layers"][name] = [keys[p] for p in KEEP]

    # Combos fire on every layer. Drawn over the base layer they cover its
    # home-row-mod hold labels, so they get their own COMBOS layer after it:
    # the base layer's tap legends with the combos on top.
    layers = parsed["layers"]
    base = next(iter(layers))
    tap_only = [{"t": k["t"]} if isinstance(k, dict) and "t" in k else k for k in layers[base]]
    parsed["layers"] = {base: layers[base], COMBOS: tap_only} | {
        name: keys for name, keys in layers.items() if name != base
    }
    for combo in parsed.get("combos", []):
        bad = [p for p in combo["p"] if p in MISSING]
        if bad:
            sys.exit(f"combo {combo}: uses positions {bad}, which the 36-key board lacks")
        combo["p"] = [NEW_INDEX[p] for p in combo["p"]]
        combo.setdefault("l", [COMBOS])

    parsed["layout"] = {"qmk_info_json": LAYOUT}
    PARSED.write_text(
        "# Generated by keymap-drawer/draw.py from toucan/toucan.keymap; do not edit.\n"
        + yaml.safe_dump(parsed, sort_keys=False, allow_unicode=True, width=200)
    )
    keymap_drawer("draw", str(PARSED), "-o", str(SVG))
    print(f"wrote {PARSED.relative_to(ROOT)} and {SVG.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
